const fs = require('fs');
const vm = require('vm');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '../app/src/main/assets/script.js'), 'utf8');
const start = src.indexOf('function normalizarObrasBackup(lista) {');
const end = src.indexOf('\nfunction criarConteudoBackup()', start);
const normSrc = src.slice(start, end);
const startKey = src.indexOf('function chaveNomeObra(nome) {');
const endKey = src.indexOf('\nfunction gerarIdImportacao', startKey);
const keySrc = src.slice(startKey, endKey);
const ctx = {};
vm.createContext(ctx);
vm.runInContext(normSrc + '\n' + keySrc, ctx);
const legacy = [{numero: 7, nome:'  Café com Leite ', scan:'Scan X', link:'https://example.com', favorita:'true', status:'Lendo', capituloLido:12, totalCapitulos:40}];
const normalized = ctx.normalizarObrasBackup(legacy);
if (normalized.length !== 1 || normalized[0].nome !== 'Café com Leite' || normalized[0].scans[0].scan !== 'Scan X' || !normalized[0].favorita) throw new Error('Falha compatibilidade legado');
const modern = ctx.normalizarObrasBackup([{id:'a',nome:'Obra',categorias:['BL','Fantasia','BL'],capitulosFavoritos:['4','8','4'],excluidaEm:'2026-01-01'}]);
if (modern[0].categorias.length !== 2 || modern[0].capitulosFavoritos.length !== 2 || !modern[0].excluidaEm) throw new Error('Falha normalização V3');
if (ctx.chaveNomeObra('Café & Ação!') !== ctx.chaveNomeObra('cafe acao')) throw new Error('Falha normalização de títulos');
console.log('OK: compatibilidade legado, campos V3, categorias/capítulos sem duplicação e comparação de títulos.');
